"""The one-page summary for faculty: docs/summary.html printed to docs/summary.pdf (A4, exactly one page).

docs/summary.html is GENERATED by 17_write_docs.py from docs/templates/summary.html.j2, so every
number in it comes from results/ (tests/test_docs.py fails if it is stale). This script only prints
it: it opens the file in Microsoft Edge through Playwright (the Edge already installed on Windows,
as 31_screenshots.py does), waits for the fonts, and saves a PDF.

Why a script and not "Print to PDF" by hand: the same file gives the same page every time, and
the script STOPS if the summary no longer fits on one page (a longer number or a new sentence can
push the last line onto page 2 without anyone noticing).

It records what it printed in results/33_summary_pdf/summary.json: the SHA-256 of the HTML (line
endings normalised, so a Windows checkout gives the same value), the page count and how much of
the page the text fills. tests/test_summary_pdf.py compares that SHA-256 with the current HTML, so
a PDF printed from an older summary is caught.

Needs Playwright (tested with 1.64.0). Not part of the tests or CI. Run from the repo root (~5 s),
after 17_write_docs.py:
    .venv\\Scripts\\python.exe experiments\\33_summary_pdf.py [--preview path.png]
"""

import argparse
import hashlib
import json
import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
HTML = REPO_ROOT / "docs" / "summary.html"
PDF = REPO_ROOT / "docs" / "summary.pdf"
OUT_DIR = REPO_ROOT / "results" / "33_summary_pdf"

# A4 minus the @page margins of the template (15 mm left/right, 13 mm top, 12 mm bottom), in CSS
# pixels (96 per inch): 180 mm wide, 272 mm tall. Example: 272 mm / 25.4 * 96 = 1028 px.
MM_TO_PX = 96 / 25.4
PRINT_WIDTH_PX = round(180 * MM_TO_PX)
PRINT_HEIGHT_PX = round(272 * MM_TO_PX)


def html_sha256(path):
    """SHA-256 of the text with Windows line endings turned into Unix ones (git may check out either)."""
    text = path.read_bytes().replace(b"\r\n", b"\n")
    return hashlib.sha256(text).hexdigest()


def count_pdf_pages(pdf_bytes):
    """Number of page objects in a PDF: each page is a dictionary with "/Type /Page" (the page TREE
    is "/Type /Pages", which the pattern excludes). Edge writes page dictionaries uncompressed.
    Example: a two-page PDF contains "/Type /Page" twice and "/Type /Pages" once -> 2.
    """
    return len(re.findall(rb"/Type\s*/Page(?![s\w])", pdf_bytes))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--preview", help="also save a PNG of the page as printed (for looking at it)")
    args = parser.parse_args()

    from playwright.sync_api import sync_playwright

    errors = []
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(channel="msedge")
        page = browser.new_page(viewport={"width": PRINT_WIDTH_PX, "height": PRINT_HEIGHT_PX})
        page.on("console", lambda m: errors.append(m.text) if m.type == "error" else None)
        page.on("requestfailed", lambda r: errors.append(f"could not load {r.url}"))
        page.emulate_media(media="print")
        page.goto(HTML.as_uri())
        page.evaluate("document.fonts.ready")
        fonts = page.evaluate("[...document.fonts].filter(f => f.status === 'loaded').map(f => f.family)")
        # the bottom edge of the text itself: the document's scrollHeight can't be smaller than the
        # window, so it would say "100 %" for any page that fits (seen on the first run)
        height = page.evaluate("Math.ceil(document.body.getBoundingClientRect().bottom)")
        if args.preview:
            page.screenshot(path=args.preview, full_page=True)
        pdf_bytes = page.pdf(format="A4", print_background=True, prefer_css_page_size=True)
        browser.close()

    if errors:
        raise SystemExit("problems while loading the summary, PDF not written:\n" + "\n".join(errors))
    if not {"Barlow", "Barlow Condensed"} <= set(fonts):
        raise SystemExit(f"the Barlow fonts did not load (loaded: {fonts}); PDF not written")
    pages = count_pdf_pages(pdf_bytes)
    if pages != 1:
        raise SystemExit(f"the summary prints on {pages} pages, not 1 ({height} px of text for "
                         f"{PRINT_HEIGHT_PX} px of page): shorten docs/templates/summary.html.j2")

    PDF.write_bytes(pdf_bytes)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    record = {"html": "docs/summary.html", "html_sha256": html_sha256(HTML), "pdf": "docs/summary.pdf",
              "pages": pages, "text_height_px": height, "page_height_px": PRINT_HEIGHT_PX,
              "page_filled": round(height / PRINT_HEIGHT_PX, 3)}
    with open(OUT_DIR / "summary.json", "w", encoding="utf-8") as file:
        json.dump(record, file, indent=1)
    print(f"wrote {PDF.relative_to(REPO_ROOT)}: {pages} page, text fills {record['page_filled']:.0%} of it")


if __name__ == "__main__":
    main()
